/**
 * Writes audit/catalogue/COVERAGE.md from the manifest, so the coverage checklist cannot drift from the data.
 *   npx tsx scripts/catalogue-coverage.ts
 * Status columns are derived, not typed by hand:
 *  - Route:     merged into an existing page, or a new route.
 *  - Page:      "live" when the canonical route is served by the site today; otherwise "to build".
 *  - Packages:  "published" when a ServiceRecord for the brief publishes its offers.
 *  - Demo:      "to build" until the family demonstration page exists.
 */
import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { briefs, families, moduleLink } from '../data/catalogue/manifest';
import { merges, canonicalRoute } from '../data/catalogue/routes';
import { catalogueServices } from '../data/catalogue/services';
import { services } from '../data/services';
import { industries } from '../data/industries';
import { solutions } from '../data/solutions';
import { allLeaves } from '../lib/catalogue/leaf';
import { mergedTierNames } from '../data/catalogue/content/merged';

const live = new Set<string>([
  ...services.map((s) => s.href),
  ...industries.map((i) => `/industries/${i.slug}`),
  ...solutions.map((s) => `/solutions/${s.slug}`),
  ...allLeaves().map((l) => l.route),
]);
const appDir = (route: string) => existsSync(join('app', route, 'page.tsx')) || existsSync(join('app', route.split('/').slice(0, -1).join('/'), '[slug]', 'page.tsx')) && route.startsWith('/demonstrations/');
const isLive = (route: string) => live.has(route) || appDir(route);
const published = new Set([...catalogueServices.filter((s) => s.publishedTiers.length).map((s) => s.route), ...allLeaves().map((l) => l.route)]);

const rows = briefs.map((b) => {
  const route = canonicalRoute(b);
  return {
    b,
    route,
    merged: Boolean(merges[b.id]),
    page: isLive(route) ? 'live' : 'to build',
    packages: published.has(route) || mergedTierNames[b.id] || ['S001', 'S002'].includes(b.id) ? 'published' : 'not yet',
    demo: appDir(moduleLink(b).split('#')[0]!) ? 'demo live' : 'to build',
  };
});

const count = (f: (r: (typeof rows)[number]) => boolean) => rows.filter(f).length;
const L: string[] = [];
L.push('# Catalogue coverage checklist', '');
L.push('Generated by `scripts/catalogue-coverage.ts` from `data/catalogue/manifest.ts`. Do not edit by hand; rerun the script.', '');
L.push(`- Briefs: ${briefs.length} (${count((r) => !r.b.id.startsWith('EXT'))} foundational, ${count((r) => r.b.id.startsWith('EXT'))} extensions); original catalogue IDs: ${new Set(briefs.map((b) => b.catalogueId).filter(Boolean)).size}`);
L.push(`- Merged into an existing page: ${count((r) => r.merged)}; new routes: ${count((r) => !r.merged)}`);
L.push(`- Page live: ${count((r) => r.page === 'live')}; to build: ${count((r) => r.page === 'to build')}`);
L.push(`- Packages published: ${count((r) => r.packages === 'published')}`);
L.push(`- Demonstration pages live: ${families.filter((f) => appDir(f.demo.route)).length} of ${families.length}. Each runs a working in-browser demonstration on invented data (components/demos) and shows each module's sample deliverable.`, '');
L.push('"live" means a page answers at the canonical route today. It does not mean the page already carries the brief\'s packages, proof and FAQs; the Packages column tracks that.', '');

for (const f of families) {
  const fr = rows.filter((r) => r.b.family === f.code);
  L.push(`## ${f.code} ${f.name} (${fr.length})`, '', `Hub: \`${f.hub}\` · Division: ${f.division} · Demo: ODOOVATIONS ${f.demo.name} \`${f.demo.route}\``, '');
  L.push('| ID | Page | Blueprint | Canonical route | Route | Page | Packages | Demo |', '|---|---|---|---|---|---|---|---|');
  for (const r of fr) {
    L.push(`| ${r.b.id} | ${r.b.title} | ${r.b.blueprint}${r.b.tiers ? ' (override)' : ''} | \`${r.route}\` | ${r.merged ? 'merged' : 'new'} | ${r.page} | ${r.packages} | ${r.demo} |`);
  }
  L.push('');
}

writeFileSync('audit/catalogue/COVERAGE.md', L.join('\n') + '\n');
